"""Apply the repair-pass output to GitHub: rewrite epic/ticket bodies, create new tickets, sync labels and blocked-by edges,
close superseded tickets. Idempotent via repair_state.json. Usage: python3 apply_repair.py <repair_result.json> [--dry-run]"""
import json, subprocess, sys, time, os, re
res=json.load(open(sys.argv[1])); dry='--dry-run' in sys.argv
nums=json.load(open('publish_state.json')); adopted=json.load(open('adopted_decisions.json')); REPO='gyldlab/keld'; SP='repair_state.json'; st=json.load(open(SP)) if os.path.exists(SP) else {}
PROV="> Generated by an AI agent (Claude Code, Fable 5.1) on behalf of @0monish during Wayfinder charting of the Electron compatibility program, 2026-10-06. Body rewritten by the doctrine-audit repair pass the same day (change log at the end). Planning only — no implementation is authorized by this issue."
def scrub(t):
    t=re.sub(r'/private/tmp/claude-501/[^\s)\]`"\']*scratchpad','<scratchpad>',t); t=re.sub(r'<prompt-tracker clone>','<prompt-tracker clone>',t)
    t=re.sub(r'<keld repo>','<keld repo>',t); return re.sub(r'<home>)\]`"\']*','<home>',t)
def gh(args, inp=None, ok_fail=False):
    for a in range(6):
        p=subprocess.run(['gh','api']+args,input=inp,capture_output=True,text=True)
        if p.returncode==0: return p.stdout
        e=p.stderr+p.stdout
        if any(x in e.lower() for x in ('rate limit','abuse','secondary')): time.sleep(min(90,10*(a+1))); continue
        if ok_fail: return None
        raise RuntimeError(e[:300])
    raise RuntimeError('retries exhausted')
def once(tag, fn):
    if st.get(tag) is True: return True
    if dry: print('[dry]',tag); return False
    try: fn(); st[tag]=True; json.dump(st,open(SP,'w'),indent=1); return True
    except RuntimeError as e: st[tag]='failed: '+str(e)[:200]; print('FAIL',tag,str(e)[:200]); json.dump(st,open(SP,'w'),indent=1); return False
def ref(k): return f"#{nums[k]['number']}" if k in nums else f"`{k}` (not published)"
def L(xs,empty='none'): xs=[x for x in (xs or []) if x and str(x).strip()]; return '\n'.join(f'- {x}' for x in xs) if xs else f'- {empty}'
TIER={'1':'compat:tier-1','2':'compat:tier-2','3':'compat:tier-3'}
def tier_label(s):
    m=re.search(r'([123])',s or ''); return TIER.get(m.group(1)) if m else None
MS={'first-proof':'milestone:first-proof','next':'milestone:next','parked':'milestone:parked'}
def ms(v):
    v=(v or '').lower()
    for k,l in MS.items():
        if k in v: return l
RS=('ready-for-agent','ready-for-human','needs-spec','needs-info','triage')
live={}
def state_of(n):
    if n not in live: live[n]=json.loads(gh([f'repos/{REPO}/issues/{n}']))
    return live[n]
# ---- pass 1: create new tickets (need numbers before bodies reference them)
for r in res['repaired']:
    u=r['unit']; ek=f'{u}-EPIC'
    for t in r['repair']['tickets']:
        k=t['key']
        if k in nums: continue
        def create(t=t,k=k,ek=ek):
            kind=(t.get('kind') or 'feature').lower(); typ='Task' if kind in ('spec','conformance','task','research') else 'Feature'
            payload={'title':t['title'][:250],'body':PROV+'\n\n(body follows)','labels':['electron-compat'],'type':typ}
            out=gh(['-X','POST',f'repos/{REPO}/issues','--input','-'],inp=json.dumps(payload)); j=json.loads(out)
            nums[k]={'number':j['number'],'id':j['id'],'node_id':j['node_id']}; json.dump(nums,open('publish_state.json','w'),indent=1)
            gh(['-X','POST',f"repos/{REPO}/issues/{nums[ek]['number']}/sub_issues",'--input','-'],inp=json.dumps({'sub_issue_id':j['id']})); time.sleep(0.8)
            print('created',k,'#',j['number'])
        once(f'create:{k}',create)
# ---- pass 2: bodies, titles, labels
