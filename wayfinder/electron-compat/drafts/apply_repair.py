    once(f'epic:{u}', lambda: (gh(['-X','PATCH',f"repos/{REPO}/issues/{nums[ek]['number']}",'--input','-'],inp=json.dumps({'title':rp['epic_title'][:250],'body':ebody})), time.sleep(0.6)))
