out('# draw.io Electron main under Bun 1.4.2: boot-and-authority trace');
out();
out('Generated by `harness/summarize.mjs` from `trace.jsonl` (packaged-like run) and `trace.unpackaged.jsonl` (dev-tree run). Path prefixes: `<APP>` = `p3/drawio-desktop`, `<HOME>` = `p3/fakehome`, `<P3>` = the experiment root. Everything was written under `p3/`; no network was available to the app (every outbound attempt is refused by the harness and recorded as `kind:"net"`).');
out();

// ---- 1. outcome -------------------------------------------------------------
const rr = primary.result;
out('## 1. Did each phase complete?');
out();
if (rr) {
	const byPhase = {};
	for (const s of rr.steps) { (byPhase[s.phase] = byPhase[s.phase] || []).push(s); }
	out('| phase | steps passed | steps failed | result |');
	out('|---|---|---|---|');
	for (const ph of PHASES) {
		const st = byPhase[ph] || [];
		const ok = st.filter((s) => s.ok).length;
		out(`| ${ph} | ${ok} | ${st.length - ok} | ${st.length && ok === st.length ? 'completed' : (st.length ? 'INCOMPLETE' : 'not reached')} |`);
	}
	out();
	out('Step-by-step (packaged-like run):');
	out();
	out('| phase | step | ok | detail |');
	out('|---|---|---|---|');
	for (const s of rr.steps) out(`| ${s.phase} | ${esc(s.step)} | ${s.ok ? 'yes' : '**NO**'} | ${esc(short(s.detail === null ? '' : s.detail, 120))} |`);
	out();
	out(`Import error: ${rr.importError ? '`' + rr.importError.message + '`' : 'none (module graph evaluated; no top-level-await failure)'}. Fatal runner error: ${rr.fatal ? rr.fatal.message : 'none'}.`);
}
out();

// ---- 2. counts ----------------------------------------------------------------
out('## 2. Event counts (authority events only: excludes driver markers, `:error` follow-ups and the harness canary)');
out();
for (const run of [primary, variant].filter(Boolean)) {
	const c = countTable(run.events);
	const title = run.suffix === '' ? 'Primary: `trace.jsonl` (app.isPackaged=true, as shipped)' : 'Variant: `trace.unpackaged.jsonl` (app.isPackaged=false, raw dev tree)';
	out(`**${title}**`);
	out();
	out('| phase | ' + KINDS.join(' | ') + ' | total |');
	out('|---|' + KINDS.map(() => '---:').join('|') + '|---:|');
	const tot = {};
	for (const ph of PHASES) {
		let row = 0;
		const cells = KINDS.map((k) => { const n = (c[ph] && c[ph][k]) || 0; tot[k] = (tot[k] || 0) + n; row += n; return n; });
		out(`| ${ph} | ${cells.join(' | ')} | ${row} |`);
	}
	out(`| **all** | ${KINDS.map((k) => tot[k] || 0).join(' | ')} | ${KINDS.reduce((a, k) => a + (tot[k] || 0), 0)} |`);
	out();
	const ops = {};
	for (const e of run.events) if (isAuthority(e) && e.kind === 'electron') ops[e.op || 'call'] = (ops[e.op || 'call'] || 0) + 1;
	const drv = run.events.filter(isDriver).length, errs = run.events.filter(isErr).length, can = run.events.filter(isCanary).length;
	out(`Electron events by op: ${Object.entries(ops).map(([k, v]) => k + '=' + v).join(', ')}. Not counted above: ${drv} driver markers, ${errs} \`:error\` follow-ups, ${can} canary events. File has ${run.events.length} lines total.`);
	out();
}

// ---- 3. electron members before the first BrowserWindow -----------------------------
out('## 3. Electron members touched before the first `new BrowserWindow`');
out();
{
	const ev = primary.events;
	const firstWin = ev.find((e) => e.kind === 'electron' && e.member_or_op === 'BrowserWindow' && e.op === 'new');
	const cutoff = firstWin ? firstWin.seq : Infinity;
	out(`First window construction is trace seq **${firstWin ? firstWin.seq : 'n/a'}** (phase ${firstWin ? firstWin.phase : '-'}; the app creates it with default \`show:true\`, so this is the "would show its first window" moment). Members in order of first touch, with every op seen and how often (the bracketed op is the first one):`);
	out();
	out('| # | first seq | phase | member | ops (count) | args (first call; for on/once/handle: every event name) | first caller |');
	out('|---:|---:|---|---|---|---|---|');
	const seen = new Map();
	for (const e of ev) {
		if (e.seq >= cutoff) break;
		if (e.kind !== 'electron' || !isAuthority(e)) continue;
		const k = e.member_or_op;
		if (!seen.has(k)) seen.set(k, { first: e, ops: {}, names: [] });
		const r = seen.get(k);
		if (/\.(on|once|handle|handleOnce)$/.test(k) && Array.isArray(e.args_shape) && typeof e.args_shape[0] === 'string' && !r.names.includes(e.args_shape[0])) r.names.push(e.args_shape[0]);
		const o = (e.op || 'call') + (e.fn_ref ? '(ref)' : '') + (e.unresolved ? '(UNRESOLVED)' : '');
		r.ops[o] = (r.ops[o] || 0) + 1;
	}
	let i = 0;
	for (const [m, r] of seen) {
		const argsCell = r.names.length ? r.names.join(', ') : (r.first.args_shape === null ? (r.first.value_shape !== undefined ? '= ' + short(r.first.value_shape, 40) : '') : short(r.first.args_shape, 60));
		out(`| ${++i} | ${r.first.seq} | ${r.first.phase} | \`${m}\` | ${Object.entries(r.ops).map(([a, b]) => a + ' x' + b).join(', ')} | ${esc(argsCell)} | ${esc(callerOf(r.first))} |`);
	}
	out();
	const libOnly = [...seen.values()].filter((r) => !r.first.caller).length;
	out(`${seen.size} distinct members. ${libOnly} of them were first touched by a dependency (electron-log, electron-store, electron-updater, electron-context-menu, electron-is-dev) rather than by \`src/main\`; \`caller\` is the first \`src/main\` frame on the stack, \`via\` the innermost non-harness frame when it is a dependency.`);
}
out();

// ---- 3b. IPC surface -----------------------------------------------------------------------------------------
out('## 3b. IPC and event surface the main process registers');
out();
{
	const ev = primary.events.filter(isAuthority);
	const chans = new Map();
	for (const e of ev) {
		const m = /^ipcMain\.(on|once|handle|handleOnce)$/.exec(e.member_or_op);
		if (!m || !Array.isArray(e.args_shape)) continue;
		const ch = String(e.args_shape[0]);
		const owner = e.via ? e.via.replace(/^pkg:/, '').split('/')[0] : (e.caller ? 'src/main' : '?'); // registering code (via) wins over the initiator (caller)
		const k = ch + '\u0001' + m[1];
		if (!chans.has(k)) chans.set(k, { ch, kind: m[1], owner, phase: e.phase, seq: e.seq, n: 0 });
		chans.get(k).n++;
	}
	out('Every `ipcMain.on/once/handle` registration (these are the renderer-reachable entry points; note the owner: dependencies register channels too):');
	out();
	out('| seq | phase | channel | kind | registered by | n |');
	out('|---:|---|---|---|---|---:|');
	for (const r of chans.values()) out(`| ${r.seq} | ${r.phase} | \`${r.ch}\` | ${r.kind} | ${r.owner}${r.owner === 'src/main' ? '' : ' (library)'} | ${r.n} |`);
	out();
	const appOn = new Map();
	for (const e of ev) {
		if (!/^(app)\.(on|once)$/.test(e.member_or_op) || !Array.isArray(e.args_shape)) continue;
		const k = String(e.args_shape[0]);
		if (!appOn.has(k)) appOn.set(k, { phase: e.phase, owner: e.via ? e.via.replace(/^pkg:/, '').split('/')[0] : (e.caller ? 'src/main' : '?') });
	}
	out('`app.on/once` events subscribed: ' + [...appOn.entries()].map(([k, v]) => '`' + k + '` (' + v.owner + ', ' + v.phase + ')').join(', ') + '.');
	out();
	// rendererReq actions: static list from source, exercised list from driver markers
	const srcPath = path.join(P3, 'drawio-desktop', 'src', 'main', 'electron.js');
	const src = fs.readFileSync(srcPath, 'utf8');
	const start = src.indexOf('switch(args.action)');
	const endIdx = src.indexOf('\n\t\t};', start);
	const block = src.slice(start, endIdx);
	const actions = [...block.matchAll(/case '([A-Za-z]+)':/g)].map((m) => m[1]);
	const klass = {
		saveFile: 'fs write (+backup, verify re-read)', writeFile: 'fs write', saveDraft: 'fs write (sibling .dtmp)', getFileDrafts: 'fs read/stat (+legacy draft rename)',
		getBkpFile: 'fs read', getDocumentsFolder: 'app.getPath', checkFileExists: 'fs stat', showOpenDialog: 'dialog + bless path', showSaveDialog: 'dialog + bless path',
		isPluginsEnabled: 'none', dirname: 'none (pure path.dirname)', readFile: 'fs read', clipboardAction: 'clipboard', deleteFile: 'fs unlink (content-sniffed)',
		fileStat: 'fs stat', isFileWritable: 'fs access', windowAction: 'window control', openExternal: 'shell.openExternal (http/https/mailto/tel/callto)',
		watchFile: 'fs.watchFile poll', unwatchFile: 'fs.unwatchFile', exit: 'app.quit', getLocalFonts: 'child_process execFile (fc-list / powershell)', isFullscreen: 'window query',
	};
	const exercised = new Set();
	for (const e of primary.events) if (e.driver && e.member_or_op === '<driver> ipc:rendererReq' && e.args_shape && e.args_shape.action) exercised.add(e.args_shape.action);
	out(`\`rendererReq\` action switch (static, from src/main/electron.js): ${actions.length} actions; ${[...exercised].filter((a) => actions.includes(a)).length} exercised in this run.`);
	out();
	out('| action | authority behind it | exercised here |');
	out('|---|---|---|');
	for (const a of actions) out(`| \`${a}\` | ${klass[a] || '?'} | ${exercised.has(a) ? 'yes' : 'no'} |`);
	out();
}

// ---- 4. authority ops by phase ----------------------------------------------------------
out('## 4. Every authority op, grouped by phase');
out();
out('fs/child_process/net/os rows are grouped by (kind, op, target) and show repeat count, first seq and the first `src/main` caller. env is listed as variable names read (values are never recorded). Electron API calls are summarised per phase in section 4b. A caller of `-` means no `src/main` frame was on the JS stack (async continuation inside a dependency, or runtime-internal).');
out();
function groupRows(events, kind) {
	const g = new Map();
	for (const e of events) {
		if (!isAuthority(e) || e.kind !== kind) continue;
		const target = norm(e.path || e.host || e.cmd || '');
		const key = [e.phase, e.member_or_op, target, e.access || '', e.blocked || ''].join('\u0001');
		if (!g.has(key)) g.set(key, { e, n: 0, target });
		g.get(key).n++;
	}
	return g;
}
for (const ph of PHASES) {
	out(`### Phase \`${ph}\``);
	out();
	for (const kind of ['fs', 'child_process', 'net', 'os']) {
		const g = groupRows(primary.events.filter((e) => e.phase === ph), kind);
		if (!g.size) { out(`- ${kind}: none`); continue; }
		out(`- **${kind}** (${[...g.values()].reduce((a, r) => a + r.n, 0)} events, ${g.size} distinct)`);
		out();
		out('| first seq | op | access | target | n | caller | note |');
		out('|---:|---|---|---|---:|---|---|');
		for (const r of g.values()) {
			const e = r.e;
			const note = e.blocked ? 'BLOCKED ' + e.blocked : (e.method ? e.method : '');
			out(`| ${e.seq} | \`${e.member_or_op}\` | ${e.access || ''} | ${esc(short(r.target, 100))} | ${r.n} | ${esc(callerOf(e))} | ${note} |`);
		}
		out();
	}
	const envNames = new Map();
	for (const e of primary.events) {
		if (!isAuthority(e) || e.kind !== 'env' || e.phase !== ph) continue;
		const k = e.member_or_op.replace('env.', '') + ' ' + (typeof e.args_shape === 'string' ? e.args_shape : JSON.stringify(e.args_shape));
		if (!envNames.has(k)) envNames.set(k, { n: 0, e });
		envNames.get(k).n++;
	}
	out(`- **env** (${[...envNames.values()].reduce((a, r) => a + r.n, 0)} events): ` + (envNames.size ? [...envNames.entries()].map(([k, r]) => '`' + k + '`' + (r.n > 1 ? ' x' + r.n : '') + ' (' + callerOf(r.e).replace(/^via /, '') + ')').join('; ') : 'none'));
	out();
}

out('### 4b. Electron API surface by phase (distinct members; counts of get/call/new/set)');
out();
for (const ph of PHASES) {
	const m = new Map();
	for (const e of primary.events) {
		if (!isAuthority(e) || e.kind !== 'electron' || e.phase !== ph) continue;
		const k = e.member_or_op;
		if (!m.has(k)) m.set(k, {});
		const o = e.op || 'call';
		m.get(k)[o] = (m.get(k)[o] || 0) + 1;
	}
	out(`- **${ph}** (${m.size} distinct): ` + [...m.entries()].map(([k, o]) => '`' + k + '`' + (Object.keys(o).length === 1 && o.call ? (o.call > 1 ? ' x' + o.call : '') : ' [' + Object.entries(o).map(([a, b]) => a + b).join(',') + ']')).join(', '));
	out();
}

