// Builds trace_summary.md from trace*.jsonl + run-result*.json (+ hand-written summary-notes.md).
// Run WITHOUT the preload:  bun --no-install harness/summarize.mjs
import fs from 'node:fs';
import path from 'node:path';

const P3 = path.resolve(import.meta.dir, '..');
const PHASES = ['import', 'boot', 'open', 'save', 'close'];
const KINDS = ['electron', 'fs', 'child_process', 'net', 'env', 'os'];

function load(suffix) {
	const tp = path.join(P3, 'trace' + suffix + '.jsonl');
	if (!fs.existsSync(tp)) return null;
	const events = fs.readFileSync(tp, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
	const rp = path.join(P3, 'harness', 'run-result' + suffix + '.json');
	const result = fs.existsSync(rp) ? JSON.parse(fs.readFileSync(rp, 'utf8')) : null;
	return { suffix, events, result };
}
const primary = load('');
const variant = load('.unpackaged');
if (!primary) throw new Error('no trace.jsonl; run harness/run.sh first');

const isCanary = (e) => e.step === 'canary';
const isDriver = (e) => e.driver === true;
const isErr = (e) => e.ev === 'err';
const isAuthority = (e) => !isCanary(e) && !isDriver(e) && !isErr(e);

const md = [];
const out = (s = '') => md.push(s);
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const short = (v, n = 110) => { const s = typeof v === 'string' ? v : JSON.stringify(v); return s.length > n ? s.slice(0, n - 1) + '...' : s; };

function norm(p) {
	if (p == null) return '';
	return String(p)
		.replace(/config\.json\.tmp-[0-9a-f]+/g, 'config.json.tmp-*')
		.replace(/\.drawio-bkp-[0-9a-f-]{36}\.tmp/g, '.drawio-bkp-<uuid>.tmp')
		.replace(/fd:\d+\(/g, 'fd(');
}
function callerOf(e) { return e.caller ? e.caller.replace(/^src\/main\//, '') : (e.via ? 'via ' + e.via.replace(/^pkg:/, '') : (e.internal ? '(runtime)' : '-')); }

function countTable(events) {
	const c = {};
	for (const e of events) {
		if (!isAuthority(e)) continue;
		c[e.phase] = c[e.phase] || {};
		c[e.phase][e.kind] = (c[e.phase][e.kind] || 0) + 1;
	}
	return c;
}

