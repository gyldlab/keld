"""Apply repair + alignment to GitHub following the mattpocock to-tickets / triage / wayfinder skills.
Usage: python3 apply_repair.py <repair_result.json> <alignment.json> [--dry-run]
- ticket bodies: to-tickets template (Parent / What to build / Acceptance criteria / Blocked by) + Keld sections; no embedded brief
- labels: electron-compat + one category role (enhancement) + exactly one triage state role + Keld modifiers (needs-spec, tier, milestone)
- comments: AGENT-BRIEF (ready-for-agent / ready-for-human) or Triage Notes (needs-info), each starting with the triage disclaimer
- new tickets created in dependency order (blockers first), as sub-issues of their epic; blocked-by edges synced
Idempotent via repair_state.json."""
