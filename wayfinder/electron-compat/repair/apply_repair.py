def scrub(t):
    t=re.sub(r'/private/tmp/claude-501/[^\s)\]`"\']*scratchpad','<scratchpad>',t); t=re.sub(r'/Users/centillionaire/WORK/keld-agent-prompts','<prompt-tracker clone>',t)
    t=re.sub(r'/Users/centillionaire/WORK/keld','<keld repo>',t); return re.sub(r'/Users/centillionaire[^\s)\]`"\']*','<home>',t)
def gh(args, inp=None):
    for a in range(6):
        p=subprocess.run(['gh','api']+args,input=inp,capture_output=True,text=True)
        if p.returncode==0: return p.stdout
        e=p.stderr+p.stdout
        if any(x in e.lower() for x in ('rate limit','abuse','secondary')): time.sleep(min(90,10*(a+1))); continue
        raise RuntimeError(e[:300])
    raise RuntimeError('retries exhausted')
PREVIEW={}
def once(tag, fn):
    if st.get(tag) is True: return
    if dry: PREVIEW[tag]=True; return
    try: fn(); st[tag]=True
    except RuntimeError as e: st[tag]='failed: '+str(e)[:200]; print('FAIL',tag,str(e)[:200])
    json.dump(st,open(SP,'w'),indent=1)
def ref(k): return f"#{nums[k]['number']}" if k in nums else f"`{k}`"
def L(xs,empty='none'): xs=[x for x in (xs or []) if x and str(x).strip()]; return '\n'.join(f'- {x}' for x in xs) if xs else f'- {empty}'
AL={i['key']:i for u in align['alignment'] for i in u['items']}
def tracker_line(k):
    a=AL.get(k)
    if not a: return '- Tracker of record: **this GitHub issue** (alignment pending); Linear reference: KEL-127'
    if a['tracker']=='linear': return f"- Tracker of record: **Linear {a['linear_issue']}** ({a['linear_status']}) — claims, status and handoffs happen there; this GitHub issue is the planning record and is linked from it. Basis: {a['evidence'][:300]}"
    return f"- Tracker of record: **this GitHub issue** (no live Linear issue covers it; owner decision #517). Claims, status and handoffs happen here under `docs/agents/workflow.md` § Tracker issue (rule lands with #520). Linear reference: {a['linear_issue']} ({a['linear_status']}) carries a link to this issue."
TIER={'1':'compat:tier-1','2':'compat:tier-2','3':'compat:tier-3'}
def tier_label(s): m=re.search(r'([123])',s or ''); return TIER.get(m.group(1)) if m else None
def ms(v):
    v=(v or '').lower()
    for k in ('first-proof','next','parked'):
        if k in v: return 'milestone:'+k
def state_role(t):
    open_blockers=[b for b in (t.get('blocked_by_keys') or []) if b in OPEN_DECISIONS]
    rs=(t.get('ready_state') or '').lower()
    if 'parked' in (t.get('milestone') or '').lower(): return 'triage', open_blockers  # parked work is not agent-grabbable (coordination.md: Todo = ready-for-agent)
    if open_blockers: return 'needs-info', open_blockers
    if rs=='ready-for-human': return 'ready-for-human', []
    if rs in ('needs-triage','triage'): return 'triage', []
    return 'ready-for-agent', []
units={r['unit']:r['repair'] for r in res['repaired']}
TITLE={i['key']:i['title'] for i in json.load(open('publish_plan.json'))['issues']}
alltickets={t['key']:(u,t) for u,r in units.items() for t in r['tickets']}
# ---- pass 1: create new tickets in dependency order (blockers first)
new=[k for k in alltickets if k not in nums]
order=[]; seen=set()
def visit(k,stack=()):
    if k in seen or k not in alltickets: return
    if k in stack: return
    for b in alltickets[k][1].get('blocked_by_keys') or []:
        if b in new: visit(b,stack+(k,))
    seen.add(k); order.append(k)
for k in sorted(new): visit(k)
for k in order:
    u,t=alltickets[k]
    def create(k=k,u=u,t=t):
        kind=(t.get('kind') or 'feature').lower(); typ='Task' if kind in ('spec','conformance','task','research') else 'Feature'
        j=json.loads(gh(['-X','POST',f'repos/{REPO}/issues','--input','-'],inp=json.dumps({'title':t['title'][:250],'body':PROV+'\n\n(body follows)','labels':['electron-compat'],'type':typ})))
        nums[k]={'number':j['number'],'id':j['id'],'node_id':j['node_id']}; json.dump(nums,open('publish_state.json','w'),indent=1)
        gh(['-X','POST',f"repos/{REPO}/issues/{nums[u+'-EPIC']['number']}/sub_issues",'--input','-'],inp=json.dumps({'sub_issue_id':j['id']})); time.sleep(0.8)
        print('created',k,'#',j['number'])
    once(f'create:{k}',create)
# ---- pass 2: epic and ticket bodies + labels
