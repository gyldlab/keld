/** Menu subrenderer called by the one existing echo-codegen owner. */
export function renderMenuBinding(source: string): string {
  const declarations = [...source.matchAll(/^menu_roles! \{([\s\S]*?)^\}/gm)];
  if (declarations.length !== 1)
    throw new Error("menu codegen: expected one owning role declaration");
  const rows = declarations[0]![1]!
    .trim()
    .split("\n")
    .map((line) => {
      const row = /^(\w+), "([a-z]+)", "([^"]*)", "([a-z]?)", ([0-7]);$/.exec(
        line.trim(),
      );
      if (!row) throw new Error("menu codegen: unsupported role row");
      return row;
    });
  if (
    rows.length === 0 ||
    new Set(rows.map((row) => row[2])).size !== rows.length ||
    new Set(rows.map((row) => row[1])).size !== rows.length
  )
    throw new Error(
      "menu codegen: missing or duplicated single-source role rows",
    );
  const faultDeclarations = [
    ...source.matchAll(/^menu_faults! \{([\s\S]*?)^\}/gm),
  ];
  if (faultDeclarations.length !== 1)
    throw new Error("menu codegen: expected one owning fault declaration");
  const faultRows = faultDeclarations[0]![1]!
    .trim()
    .split("\n")
    .map((line) => {
      const row = /^(\w+), "(KELD-[A-Z]+-\d+)", "([^"]*)", "([^"]*)";$/.exec(
        line.trim(),
      );
      if (!row) throw new Error("menu codegen: unsupported fault row");
      return row;
    });
  if (
    new Set(faultRows.map((row) => row[1])).size !== faultRows.length ||
    new Set(faultRows.map((row) => row[2])).size !== faultRows.length
  )
    throw new Error("menu codegen: duplicate fault name/code");
  const expected: Record<string, string> = {
    "enum MenuKind": "Normal,Separator,Submenu,Checkbox,",
    "enum MenuAction": "NativeRole(MenuRole),UnsupportedClick,Inert,",
    "struct MenuNodeV1":
      "pub depth:u8,pub kind:MenuKind,pub label:String,pub enabled:bool,pub checked:Option<bool>,pub action:MenuAction,",
    "struct MenuRequestV1":
      '#[serde(deserialize_with="deserialize_menu_nodes")]pub nodes:Vec<MenuNodeV1>,',
    "struct MenuInstallReceipt": "pub generation:u64,",
  };
  for (const [name, shape] of Object.entries(expected)) {
    const matches = [
      ...source.matchAll(
        new RegExp("^pub " + name + " \\{([\\s\\S]*?)^\\}", "gm"),
      ),
    ];
    if (
      matches.length !== 1 ||
      matches[0]![1]!.replace(/\/\/[^\n]*/g, "").replace(/\s/g, "") !==
        shape.replace(/\s/g, "")
    )
      throw new Error("menu codegen: schema differs at " + name);
  }
  for (const declaration of [
    "pub const MAX_MENU_NODES: usize = 256;",
    "pub const MAX_MENU_DEPTH: u8 = 8;",
    "pub const MAX_MENU_LABEL_BYTES: usize = 4096;",
    "pub const MAX_MENU_REQUEST_BYTES: usize = 128 * 1024;",
  ])
    if (!source.includes(declaration))
      throw new Error("menu codegen: unreviewed bounds");
  const roleEntries = rows.map((row, id) => {
    const mask = Number(row[5]);
    const accelerator =
      row[4] === ""
        ? null
        : [
            ...(mask & 1 ? ["Command"] : []),
            ...(mask & 4 ? ["Option"] : []),
            ...(mask & 2 ? ["Shift"] : []),
            row[4]!.toUpperCase(),
          ].join("+");
    return (
      JSON.stringify(row[2]) +
      ": Object.freeze(" +
      JSON.stringify({
        id,
        label: row[3],
        key: row[4],
        modifiers: mask,
        accelerator,
      }) +
      ")"
    );
  });
  return `// @generated by packages/@keld/kipc/scripts/echo-codegen.ts.
// Source: crates/keld-native/src/menu.rs. Do not edit by hand.
import { decodeU64Varint, encodeVarint, encodePostcardString, linkError } from "@keld/kipc";
export const MENU_ROLES = Object.freeze({ ${roleEntries.join(",\n")} });
export const MENU_FAULTS = Object.freeze({ ${faultRows.map((row) => JSON.stringify(row[1]) + ": Object.freeze(" + JSON.stringify({ code: row[2], message: row[3], fix: row[4] }) + ")").join(",\n")} });
export type MenuRoleName = keyof typeof MENU_ROLES;
export type MenuKind = "Normal" | "Separator" | "Submenu" | "Checkbox";
export type MenuAction = { variant: "NativeRole"; role: MenuRoleName } | { variant: "UnsupportedClick" } | { variant: "Inert" };
export interface MenuNodeV1 { readonly depth: number; readonly kind: MenuKind; readonly label: string; readonly enabled: boolean; readonly checked: boolean | null; readonly action: MenuAction }
export interface MenuRequestV1 { readonly nodes: readonly MenuNodeV1[] }
export interface MenuInstallReceipt { readonly generation: bigint }
function invalid(detail: string): never { throw linkError("KELD-IPC-003", detail); }
/** Actual bounded Postcard encoder; no guessed JSON-size envelope. */
export function encodeMenuRequest(request: MenuRequestV1): Uint8Array {
  if (!request || !Array.isArray(request.nodes) || request.nodes.length > 256) return invalid("menu node count exceeds its bound");
  const nodes: readonly MenuNodeV1[] = request.nodes;
  const parts: Uint8Array[] = [encodeVarint(nodes.length)];
  let total = parts[0]!.length;
  const append = (bytes: Uint8Array): void => { total += bytes.length; if (total > 128 * 1024) invalid("menu envelope exceeds 128 KiB"); parts.push(bytes); };
  let prior: MenuNodeV1 | undefined;
  for (const node of nodes) {
    if (!node || !Number.isInteger(node.depth) || node.depth < 0 || node.depth > 8 || (!prior && node.depth !== 0) || (prior && (node.depth > prior.depth + 1 || (node.depth === prior.depth + 1 && prior.kind !== "Submenu")))) return invalid("menu preorder depth is invalid");
    const kind = ["Normal", "Separator", "Submenu", "Checkbox"].indexOf(node.kind);
    if (kind < 0 || typeof node.enabled !== "boolean" || typeof node.label !== "string" || !node.label.isWellFormed() || node.label.includes("\\0") || Buffer.byteLength(node.label, "utf8") > 4096) return invalid("menu kind/label/enabled is invalid");
    if ((node.kind === "Checkbox") !== (node.checked !== null) || (node.checked !== null && typeof node.checked !== "boolean")) return invalid("menu check state is invalid");
    const action = node.action;
    if (!action || ((node.kind === "Separator" || node.kind === "Submenu") && action.variant !== "Inert") || (node.kind !== "Normal" && action.variant === "NativeRole")) return invalid("menu kind/action combination is invalid");
    append(new Uint8Array([node.depth])); append(encodeVarint(kind)); append(encodePostcardString(node.label, "menu label"));
    append(new Uint8Array([node.enabled ? 1 : 0]));
    append(node.checked === null ? new Uint8Array([0]) : new Uint8Array([1, node.checked ? 1 : 0]));
    if (action.variant === "NativeRole") {
      if (!Object.hasOwn(MENU_ROLES, action.role)) return invalid("menu role is not declared");
      append(new Uint8Array([0])); append(encodeVarint(MENU_ROLES[action.role].id));
    } else if (action.variant === "UnsupportedClick") append(new Uint8Array([1]));
    else if (action.variant === "Inert") append(new Uint8Array([2]));
    else return invalid("menu action is invalid");
    prior = node;
  }
  return Buffer.concat(parts, total);
}
/** Decode the actual Host-minted generation; zero/trailing/malformed is never success. */
export function decodeMenuInstallReceipt(payload: Uint8Array): MenuInstallReceipt {
  try {
    const [generation, end] = decodeU64Varint(payload, 0);
    if (generation === 0n || end !== payload.length) return invalid("invalid native menu installation receipt");
    return Object.freeze({ generation });
  } catch { return invalid("invalid native menu installation receipt"); }
}
`;
}
