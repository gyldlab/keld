import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { createHash } from "node:crypto";

// Same package-owned Bun generation pattern as the canonical kipc codegen.
// The generated browser code is never hand-edited or read from the app tree.
const root = resolve(import.meta.dir, "../../../..");
const entry = resolve(root, "packages/@keld/electron/src/preload-runtime.ts");
const codec = resolve(root, "packages/@keld/kipc/src/endpoint-value-codec.ts");
const generator = resolve(import.meta.dir, "preload-runtime-codegen.ts");
const output = resolve(
  root,
  "crates/keld-wv/src/wkwebview/macos_preload_runtime.generated.js",
);
const digest = (path: string) =>
  createHash("sha256").update(readFileSync(path)).digest("hex");
const mode = process.argv[2];
if (mode !== "generate" && mode !== "check")
  throw new Error("use generate or check");
if (Bun.version !== "1.4.4")
  throw new Error("preload runtime generator requires pinned Bun 1.4.4");
const result = await Bun.build({
  entrypoints: [entry],
  target: "browser",
  format: "iife",
  minify: false,
  sourcemap: "none",
});
if (!result.success || result.outputs.length !== 1)
  throw new Error("browser preload bundle failed: " + result.logs.join("; "));
const unformatted = `// @generated by packages/@keld/electron/scripts/preload-runtime-codegen.ts; DO NOT EDIT.
// Bun ${Bun.version}; runtime-sha256 ${digest(entry)}; codec-sha256 ${digest(codec)}; generator-sha256 ${digest(generator)}
${await result.outputs[0]!.text()}`;
// Match the canonical kipc generator: one owner formats before write or comparison.
const formatted = Bun.spawnSync(
  [process.execPath, "fmt", "--no-script", "--stdin-filepath", output],
  { cwd: root, stdin: Buffer.from(unformatted) },
);
if (formatted.exitCode !== 0)
  throw new Error(
    "preload runtime native formatting failed: " + formatted.stderr,
  );
const generated = formatted.stdout.toString();
if (mode === "generate") writeFileSync(output, generated);
else if (readFileSync(output, "utf8") !== generated)
  throw new Error(
    "embedded preload runtime is stale; run pinned generate then check",
  );
console.log(
  `preload-runtime ${mode}: ${createHash("sha256").update(generated).digest("hex")}`,
);
