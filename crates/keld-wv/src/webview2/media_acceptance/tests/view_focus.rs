fn focus_parent(hwnd: HWND) -> Result<(), WvError> {
    // SAFETY: both are live windows created by this fixture on its UI thread.
    // API return is the previous HWND and can be null; independent getters below
    // prove the effect instead of interpreting null as failure or success.
    // https://learn.microsoft.com/windows/win32/api/winuser/nf-winuser-setactivewindow
    // https://learn.microsoft.com/windows/win32/api/winuser/nf-winuser-setfocus
    // SAFETY: D11 is the owning UI thread's active-window contract, not a
    // global foreground grant. The native loss/gain edge is observed through
    // Tao and independent GetFocus/IsChild reads. Never seize system foreground.
    unsafe {
        let _ = SetActiveWindow(hwnd);
        let _ = SetFocus(None);
        let _ = SetFocus(Some(hwnd));
    }

    println!(
        "KELD_FOCUS_NATIVE_INPUT requested={hwnd:?} active={:?} focus={:?} foreground={:?}",
        unsafe { GetActiveWindow() },
        unsafe { GetFocus() },
        unsafe { GetForegroundWindow() }
    );
    if unsafe { GetActiveWindow() } != hwnd || unsafe { GetFocus() } != hwnd {
        return Err(failure(
            "native focus stimulus did not establish same-thread activation/parent focus",
        ));
    }
    Ok(())
}

fn require_stale_focus_preserves_other(
    view: &crate::webview2::View,
    other: HWND,
    hello: bool,
) -> Result<(), WvError> {
    // A buffered earlier target event may run before this comparator event.
    // Establish the exact adverse input once immediately before injecting stale
    // target focus; native getters, not event queue ordering, verify that input.
    focus_parent(other)?;
    if unsafe { GetActiveWindow() } != other || unsafe { GetFocus() } != other {
        return Err(failure(
            "native comparator event lost its same-thread focus input",
        ));
    }
    // Deliberately inject a stale event at the existing live View
    // owner. Actual OS activation belongs to the other window.
    view.handle_host_window_event(&WindowEvent::Focused(true));
    if unsafe { GetActiveWindow() } != other || unsafe { GetFocus() } != other {
        return Err(failure(
            "stale Focused(true) stole native focus from the active window",
        ));
    }
    println!("KELD_HOST_FOCUS_STALE hello={hello} active_other=true focus_other=true");
    Ok(())
}

fn require_native_child_focus(
    view: &crate::webview2::View,
    hwnd: HWND,
    hello: bool,
) -> Result<(), WvError> {
    let active = unsafe { GetActiveWindow() };
    let focus = unsafe { GetFocus() };
    let child = unsafe { IsChild(hwnd, focus) }.as_bool();
    println!(
        "KELD_HOST_FOCUS_EVENT hello={hello} active={active:?} focus={focus:?} target={hwnd:?} child={child}"
    );
    if active != hwnd || focus == hwnd || !child {
        return Err(failure(
            "native focus did not reach the active WebView child",
        ));
    }
    // Focused(false) may be generated by transfer to the child;
    // it must not erase the still-active top-level native fact.
    view.handle_host_window_event(&WindowEvent::Focused(false));
    if unsafe { GetActiveWindow() } != hwnd || unsafe { GetFocus() } != focus {
        return Err(failure(
            "Focused(false) changed the active native WebView focus",
        ));
    }
    Ok(())
}

fn comparator_window(
    engine: &crate::webview2::WebView2Engine,
) -> Result<tao::window::Window, WvError> {
    let event_loop = engine
        .event_loop
        .as_ref()
        .ok_or_else(|| failure("test event loop already consumed"))?;
    tao::window::WindowBuilder::new()
        .with_title("KELD native focus comparator")
        .with_inner_size(tao::dpi::LogicalSize::new(320.0, 200.0))
        .build(event_loop)
        .map_err(failure)
}

fn focus_case(hello: bool) -> Result<(), WvError> {
    let root = profile_fixture_root("host-focus");
    std::fs::create_dir_all(&root).map_err(failure)?;
    println!("KELD_HOST_FOCUS_ROOT {}", root.display());
    let profile = EphemeralProfile::from_host_random([92; 32])?;
    let mut engine = profile_fixture_engine(&root, WebProfileSelection::ephemeral_dev(profile))?;
    let (events, _event_rx) = mpsc::channel();
    let target = if hello {
        engine.create(&blank_spec())?
    } else {
        engine.create_app(&blank_spec(), events.clone())?
    };
    // Plain native comparator: no second WebView can participate in a mutated
    // focus policy or create recursive controller-to-controller focus transfers.
    let alternate = comparator_window(&engine)?;
    let hwnd = HWND(engine.views[&target.0].window.hwnd() as _);
    let other = HWND(alternate.hwnd() as _);
    let target_window_id = engine.views[&target.0].window.id();
    let alternate_window_id = alternate.id();
    let (commands, receiver) = mpsc::channel();
    let verdict = Rc::new(RefCell::new(None));
    let outcome = Rc::clone(&verdict);
    let observed_events = Rc::new(Cell::new(0_u32));
    let observed = Rc::clone(&observed_events);
    let mut stage = 0;
    let limit = Instant::now() + Duration::from_secs(10);
    let hook = host_window_probe::install(Box::new(move |point, views, flow| {
        if stage == 4 {
            return;
        }
        let result = (|| -> Result<(), WvError> {
            if Instant::now() >= limit {
                return Err(failure("native active-focus event deadline"));
            }
            match (stage, point) {
                (0, host_window_probe::Point::Idle) => {
                    // Input failure stays inside the live loop so normal release
                    // and cleanup still run; never escape early from a live engine.
                    stage = 1;
                    focus_parent(hwnd)?;
                }
                (1, host_window_probe::Point::Focused(id, true)) if id == target_window_id => {
                    require_native_child_focus(&views[&target.0], hwnd, hello)?;
                    println!("KELD_HOST_FOCUS_INITIAL_EDGE hello={hello} native=true");
                    stage = 2;
                    focus_parent(other)?;
                }
                (2, host_window_probe::Point::Focused(id, true)) if id == alternate_window_id => {
                    println!("KELD_HOST_FOCUS_ALTERNATE_EDGE hello={hello} native=true");
                    require_stale_focus_preserves_other(&views[&target.0], other, hello)?;
                    stage = 3;
                    focus_parent(hwnd)?;
                }
                (3, host_window_probe::Point::Focused(id, true)) if id == target_window_id => {
                    observed.set(observed.get() + 1);
                    require_native_child_focus(&views[&target.0], hwnd, hello)?;
                    stage = 4;
                    *outcome.borrow_mut() = Some(Ok(()));
                }
                _ => {}
            }
            Ok(())
        })();
        if let Err(error) = result {
            stage = 4;
            *outcome.borrow_mut() = Some(Err(error));
        }
        if stage == 4 {
            if hello {
                // SAFETY: post close to the target; the real hello loop must retire
                // its last WebView and receive browser exit. Comparator stays owned.
                unsafe {
                    let _ = PostMessageW(Some(hwnd), WM_CLOSE, WPARAM(0), LPARAM(0));
                }
            } else {
                let _ = commands.send(AppWindowCommand::Quit);
            }
        } else {
            *flow = ControlFlow::WaitUntil((Instant::now() + Duration::from_millis(10)).min(limit));
        }
    }));
    let release = if hello {
        engine.run_until_closed()
    } else {
        run_renderer_until_quit(engine, receiver, events)
    };
    drop(hook);
    drop(alternate);
    let observation = verdict
        .borrow_mut()
        .take()
        .unwrap_or_else(|| Err(failure("native focus probe did not complete")));
    let cleanup = std::fs::remove_dir_all(&root).map_err(failure);
    if cleanup.is_ok() {
        println!("KELD_HOST_FOCUS_CLEANED {}", root.display());
    }
    println!(
        "KELD_HOST_FOCUS_NATIVE_EVENT_COUNT hello={hello} count={}",
        observed_events.get()
    );
    if let Err(error) = &release {
        eprintln!("KELD_HOST_FOCUS_RELEASE_ERROR {error}");
    }
    if let Err(error) = &cleanup {
        eprintln!("KELD_HOST_FOCUS_CLEANUP_ERROR {error}");
    }
    observation.and(release).and(cleanup)
}

#[test]
#[ignore = "real Windows app activation/stale-event/child-focus controls"]
fn windows_app_view_native_active_focus() -> Result<(), WvError> {
    run_with_watchdog(FIXTURE_DEADLINE, || focus_case(false))
}
#[test]
#[ignore = "real Windows hello activation/stale-event/child-focus controls"]
fn windows_hello_view_native_active_focus() -> Result<(), WvError> {
    run_with_watchdog(FIXTURE_DEADLINE, || focus_case(true))
}
